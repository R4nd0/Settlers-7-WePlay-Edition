'use strict';
const assert = require('node:assert/strict');
const Stepping = require('./stepping');
const p = new Stepping();
p.setBreakpoints([{ source: '@Script\\localState.lua', line: 12 }]);
assert.equal(p.reason('Script/localState.lua', 12, 3), 'breakpoint');
assert.equal(p.reason('Script/other.lua', 12, 3), null);
assert.equal(p.reason('Script/localState.lua', 13, 3), null);
p.resume('stepIn', 3);
assert.equal(p.reason('child.lua', 2, 4), 'stepIn');
p.resume('next', 3);
assert.equal(p.reason('child.lua', 2, 4), null);
assert.equal(p.reason('recursive.lua', 2, 5), null);
assert.equal(p.reason('parent.lua', 8, 3), 'next');
assert.equal(p.reason('outer.lua', 10, 2), 'next');
p.resume('stepOut', 4);
assert.equal(p.reason('child.lua', 9, 4), null);
assert.equal(p.reason('deeper.lua', 3, 5), null);
assert.equal(p.reason('parent.lua', 10, 3), 'stepOut');
assert.equal(p.reason('Script/localState.lua', 12, 6), 'breakpoint');
p.resume('continue', 0);
assert.equal(p.reason('parent.lua', 10, 3), null);
assert.throws(() => p.resume('eval', 1));
assert.throws(() => p.setBreakpoints([{ source: 'x', line: 0 }]));
assert.throws(() => p.setBreakpoints(Array(33).fill({ source: 'x', line: 1 })));
console.log('16 breakpoint/step policy checks passed');
